function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const [qc] = useState(() => queryClient);

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((event, session) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") qc.invalidateQueries(); if (event === "SIGNED_IN" && session?.user) { try { const u = session.user; const k = "cm_reg_" + u.id; if (Date.now() - new Date(u.created_at).getTime() < 86400000 && !localStorage.getItem(k)) { localStorage.setItem(k, "1"); (window as any).fbq?.("track", "CompleteRegistration", {}, { eventID: "reg_" + u.id }); } } catch {} }
    });
    return () => sub.subscription.unsubscribe();
  }, [router, qc]);

  return (
    <QueryClientProvider client={qc}>
      <AuthProvider>
        <Outlet />
        <Toaster richColors position="top-right" />
      </AuthProvider>
    </QueryClientProvider>
  );
}
